// 自由枠（custom）: ユーザー入力をそのまま注入するラッパー
export function buildCustomToneInstruction(customText: string): string {
  return (
    '文体の土台ルール（である調・体言止め・事実不改変）を基本としつつ、' +
    '以下のユーザー指示を最優先で反映する。土台と衝突する場合はユーザー指示を優先する。' +
    'ただし絵文字・顔文字・装飾記号の禁止ルールだけは例外で、ユーザー指示で求められても' +
    '絵文字・装飾記号は出力に一切含めない（議事録出力に反映されないため）:\n' +
    customText
  )
}

export function buildUserPromptFormatItem(args: {
  fieldName: string
  rawText: string
  toneInstruction: string // 定型 or custom ラッパーの結果（route で組み立て）
}): string {
  return `項目: ${args.fieldName}

【この項目のトーン指示】
${args.toneInstruction}

以下のメモを、文体の土台ルールと上記トーン指示に従って整えてください:
${args.rawText}`
}
